// Dados sintéticos de portfólio: nenhum paciente, fornecedor ou credencial real.
import { expect, test } from '@playwright/test'
import { operationalApi } from './support/operational-api'

test('paciente → agenda → atendimento com exames → conclusão e retorno gratuito', async ({ page }, testInfo) => {
  test.setTimeout(120000)
  const api = await operationalApi(page)
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  async function catalog(path: string, name: string, price?: string) {
    await page.goto('/configuracoes/' + path)
    await page.getByRole('button', { name: '+ Novo cadastro', exact: true }).click()
    await page.getByLabel('Nome', { exact: true }).fill(name)
    if (price !== undefined) await page.getByLabel('Valor padrão (R$)').fill(price)
    await page.getByRole('button', { name: 'Salvar cadastro', exact: true }).click()
    await expect(page.getByText('Cadastro salvo com sucesso.')).toBeVisible()
  }
  async function patient() {
    await page.getByRole('combobox', { name: 'Paciente', exact: true }).fill('Paciente de teste')
    await page.getByRole('option', { name: /Paciente de teste/ }).click()
  }
  try {
    await page.goto('/login')
    await page.getByLabel('E-mail', { exact: true }).fill('admin@example.test')
    await page.getByLabel('Senha', { exact: true }).fill('somente-fixture-local-1234')
    await page.getByRole('button', { name: 'Entrar no sistema' }).click()
    await expect(page.getByRole('heading', { name: 'OPTOCOM Visão', exact: true })).toBeVisible()
    await catalog('profissionais', 'Profissional de teste')
    await catalog('consultas', 'Avaliação de teste', '180,00')
    await catalog('consultas', 'Retorno de teste', '0,00')
    await catalog('exames', 'Exame de teste A', '80,00')
    await catalog('exames', 'Exame de teste B', '40,00')
    await page.goto('/pacientes')
    await page.getByRole('button', { name: '+ Novo paciente' }).click()
    await page.getByLabel('Nome completo').fill('Paciente de teste')
    await page.getByLabel('Telefone', { exact: true }).fill('(51) 99999-0001')
    await page.getByLabel('Data de nascimento (opcional)').fill('1990-05-15')
    await page.getByLabel('Observação administrativa (opcional)').fill('Cadastro fictício somente no banco local de testes.')
    await page.getByRole('button', { name: 'Salvar paciente' }).click()
    await expect(page.getByText('Paciente salvo com sucesso.')).toBeVisible()
    await page.getByRole('button',{name:'Fechar cadastro',exact:true}).click()
    await page.getByLabel('Pesquisar por nome ou telefone').fill('999990001')
    await expect(page.getByRole('button', { name: 'Paciente de teste', exact: true })).toBeVisible()
    await page.goto('/agenda')
    await page.getByLabel('Dia da agenda').fill('2026-11-03')
    await page.getByRole('button', { name: '+ Novo agendamento' }).click()
    await patient()
    await page.getByLabel('Profissional', { exact: true }).selectOption({ label: 'Profissional de teste' })
    await page.getByLabel('Tipo de consulta', { exact: true }).selectOption({ label: 'Avaliação de teste' })
    await page.getByLabel('Horário', { exact: true }).fill('09:00')
    await page.getByLabel('Status', { exact: true }).selectOption('confirmed')
    await page.getByRole('button', { name: 'Salvar agendamento' }).click()
    await expect(page.getByText('Agendamento salvo com sucesso.')).toBeVisible()
    await page.getByRole('button', { name: 'Iniciar atendimento', exact: true }).click()
    await expect(page.getByLabel('Valor da consulta (R$)')).toHaveValue('180,00')
    await page.getByLabel('Desconto da consulta (R$)').fill('20,00')
    for (const name of ['Exame de teste A', 'Exame de teste B']) {
      const options = await page.getByLabel('Adicionar exame', { exact: true }).locator('option').allTextContents()
      await page.getByLabel('Adicionar exame', { exact: true }).selectOption({ label: options.find(o => o.startsWith(name))! })
      await page.getByRole('button', { name: '+ Adicionar exame', exact: true }).click()
    }
    await expect(page.locator('.total-line')).toContainText('280,00')
    await page.getByLabel('Valor de Exame de teste A (R$)').fill('90,00')
    await expect(page.locator('.total-line')).toContainText('290,00')
    await page.getByLabel('Valor de Exame de teste A (R$)').fill('80,00')
    await page.getByRole('button', { name: 'Salvar rascunho', exact: true }).click()
    await expect(page.getByText('Rascunho salvo com sucesso.')).toBeVisible()
    await page.evaluate(() => window.scrollTo(0, 0))
    await page.screenshot({ path: testInfo.outputPath('atendimento-com-exames.png'), fullPage: true })
    await page.getByRole('button', { name: 'Concluir atendimento', exact: true }).click()
    await expect(page.getByText('Atendimento concluído com sucesso.')).toBeVisible()
    await expect(page.getByRole('button', { name: 'Concluir atendimento', exact: true })).toHaveCount(0)
    await page.goto('/agenda')
    await page.getByLabel('Dia da agenda').fill('2026-11-03')
    await expect(page.getByText('Atendido', { exact: true })).toBeVisible()
    await page.screenshot({ path: testInfo.outputPath('agenda-atendido.png'), fullPage: true })
    await page.goto('/pacientes')
    await page.getByRole('button', { name: 'Paciente de teste', exact: true }).click()
    await expect(page.getByRole('heading', { name: 'Histórico administrativo de atendimentos' })).toBeVisible()
    await expect(page.locator('.history-item')).toContainText('Concluído')
    await page.goto('/novo-atendimento')
    await patient()
    await page.getByLabel('Profissional responsável').selectOption({ label: 'Profissional de teste' })
    await page.getByLabel('Tipo de consulta', { exact: true }).selectOption({ label: 'Retorno de teste' })
    await expect(page.getByLabel('Valor da consulta (R$)')).toHaveValue('0,00')
    await page.getByRole('button', { name: 'Concluir atendimento', exact: true }).click()
    await expect(page.getByText('Concluído', { exact: true })).toBeVisible()
    await page.goto('/atendimentos')
    await expect(page.getByRole('cell', { name: 'Retorno de teste', exact: true })).toBeVisible()
    await page.goto('/pacientes')
    await page.getByRole('button', { name: 'Paciente de teste', exact: true }).click()
    await page.getByLabel('Telefone', { exact: true }).fill('(51) 99999-0001')
    await page.getByRole('checkbox', { name: 'Paciente ativo' }).uncheck()
    page.once('dialog',dialog=>{expect(dialog.message()).toContain('Paciente de teste');return dialog.accept()})
    await page.getByRole('button', { name: 'Salvar paciente' }).click()
    await expect(page.getByText('Paciente salvo com sucesso.')).toBeVisible()
    await expect(page.locator('.history-item')).toHaveCount(2)
    await page.getByRole('button',{name:'Fechar cadastro',exact:true}).click()
    await expect(page.getByRole('button', { name: 'Paciente de teste', exact: true })).toHaveCount(0)
    await page.getByLabel('Mostrar também pacientes inativos').check()
    await expect(page.getByText('Inativo', { exact: true })).toBeVisible()
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true)
    expect(api.unexpected).toEqual([])
    expect(errors).toEqual([])
  } finally { await api.close() }
})
